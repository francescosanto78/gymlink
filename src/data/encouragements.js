const ORDINALS_IT = [
  'Primo', 'Secondo', 'Terzo', 'Quarto', 'Quinto',
  'Sesto', 'Settimo', 'Ottavo', 'Nono', 'Decimo'
];

const ORDINALS_EN = [
  'First', 'Second', 'Third', 'Fourth', 'Fifth',
  'Sixth', 'Seventh', 'Eighth', 'Ninth', 'Tenth'
];

const ORDINALS_ES = [
  'Primer', 'Segundo', 'Tercer', 'Cuarto', 'Quinto',
  'Sexto', 'Séptimo', 'Octavo', 'Noveno', 'Décimo'
];

/**
 * Restituisce il titolo ordinale dell'esercizio appena completato (es. "Primo esercizio completato!")
 */
export function getExerciseCompletedHeading(zeroBasedIndex, lang = 'it') {
  if (lang === 'en') {
    const ord = ORDINALS_EN[zeroBasedIndex] || `${zeroBasedIndex + 1}th`;
    return `${ord} exercise completed!`;
  }
  if (lang === 'es') {
    const ord = ORDINALS_ES[zeroBasedIndex] || `${zeroBasedIndex + 1}º`;
    return `¡${ord} ejercicio completado!`;
  }
  const ord = ORDINALS_IT[zeroBasedIndex] || `${zeroBasedIndex + 1}°`;
  return `${ord} esercizio completato!`;
}

/**
 * Estrae una frase motivazionale casuale evitando ripetizioni rispetto a usedIndicesSet
 */
export function pickRandomEncouragement(lang = 'it', usedIndicesSet = null) {
  const pool =
    lang === 'en' ? ENCOURAGEMENTS_EN : lang === 'es' ? ENCOURAGEMENTS_ES : ENCOURAGEMENTS_IT;

  const available = [];
  for (let i = 0; i < pool.length; i++) {
    if (!usedIndicesSet || !usedIndicesSet.has(i)) {
      available.push(i);
    }
  }

  const candidates = available.length > 0 ? available : pool.map((_, idx) => idx);
  if (available.length === 0 && usedIndicesSet) {
    usedIndicesSet.clear();
  }

  const chosenIndex = candidates[Math.floor(Math.random() * candidates.length)];
  if (usedIndicesSet) {
    usedIndicesSet.add(chosenIndex);
  }
  return {
    text: pool[chosenIndex],
    index: chosenIndex
  };
}
